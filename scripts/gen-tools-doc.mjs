// Writes docs/tools.md from the MCP server's own tool list, so the
// reference can't drift from the code.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';

const home = fs.mkdtempSync(path.join(os.tmpdir(), 'proofloop-doc-'));
const client = new Client({ name: 'doc', version: '1' });
await client.connect(new StdioClientTransport({ command: process.execPath, args: [path.resolve('src/server.mjs')], cwd: home, env: { ...process.env, HOME: home } }));
const { tools } = await client.listTools();
await client.close();
fs.rmSync(home, { recursive: true, force: true });
const out = ['# MCP tool reference', '', 'Generated by `node scripts/gen-tools-doc.mjs`. The skills call these tools; you rarely need them directly.', ''];
for (const t of tools) {
  out.push(`## ${t.name}`, '', t.description, '');
  const props = t.inputSchema?.properties ?? {};
  const req = new Set(t.inputSchema?.required ?? []);
  const rows = Object.entries(props).map(([k, v]) => `| \`${k}\` | ${v.type ?? (v.anyOf ? 'one of' : v.enum ? 'enum' : 'object')}${v.enum ? `: ${v.enum.join(', ')}` : ''} | ${req.has(k) ? 'yes' : ''} | ${(v.description ?? '').replace(/\|/g, '\\|')} |`);
  if (rows.length) out.push('| Parameter | Type | Required | Notes |', '|---|---|---|---|', ...rows, '');
}
fs.writeFileSync('docs/tools.md', out.join('\n'));
console.log(`docs/tools.md: ${tools.length} tools`);
