// Bundles the web pages (participant runner, Studio, board) into one JS
// module of strings, so the MCP server can serve and copy them without
// reading files relative to an install path.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
// fileURLToPath decodes %20 and the like, so paths with spaces work.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const webDir = path.join(root, 'src/web');
const out = {};
for (const sub of ['runner', 'local']) {
  for (const f of fs.readdirSync(path.join(webDir, sub)).sort()) out[`${sub}/${f}`] = fs.readFileSync(path.join(webDir, sub, f), 'utf8');
}
fs.writeFileSync(path.join(root, 'src/lib/web-assets.generated.mjs'), `// Generated by scripts/gen-assets.mjs. Do not edit.\nexport const WEB = ${JSON.stringify(out, null, 0)};\n`);
console.log(`web assets: ${Object.keys(out).length} files`);
